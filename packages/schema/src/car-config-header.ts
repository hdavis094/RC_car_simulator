import type { Car } from './car.ts';
import type { Catalog } from './catalog.ts';
import { hex, macroName } from './common.ts';
import type { IssueRef } from './wiring/issue.ts';
import { Netlist, type ResolvedPart } from './wiring/netlist.ts';

/** One `#define` of the car config header. */
export interface HeaderMacro {
  readonly name: string;
  readonly value: string;
  readonly part: ResolvedPart;
  /** The part, or part pin, the macro comes from (for issue refs). */
  readonly ref: IssueRef;
}

/**
 * Every part macro the header defines, in output order: one per signal pin
 * that reaches a GPIO (`TOF_LEFT_XSHUT_PIN`), the I²C address, and divider
 * resistor values. All end in `_PIN`, `_I2C_ADDR` or `_OHM`, so none can
 * collide with the header's own `CAR_CONFIG_H` and `CAR_WIFI_ENABLED`.
 */
export function headerMacros(netlist: Netlist): HeaderMacro[] {
  const macros: HeaderMacro[] = [];
  for (const part of netlist.parts) {
    const definition = part.definition;
    const id = part.instance.instanceId;
    const prefix = macroName(id);
    for (const pin of definition.pins) {
      if (pin.kind === 'gnd' || pin.kind === 'power-in' || pin.kind === 'power-out') continue;
      const gpio = netlist.gpioOfPin(part, pin.name);
      if (gpio === undefined) continue;
      macros.push({
        name: `${prefix}_${macroName(pin.name)}_PIN`,
        value: String(gpio),
        part,
        ref: { part: id, pin: pin.name },
      });
    }
    if ('i2c' in definition && definition.i2c) {
      macros.push({
        name: `${prefix}_I2C_ADDR`,
        value: hex(part.instance.i2cAddress ?? definition.i2c.defaultAddress),
        part,
        ref: { part: id },
      });
    }
    if ('behavior' in definition && definition.behavior.template === 'voltage-divider') {
      const { r1Ohm, r2Ohm } = definition.behavior.params;
      macros.push(
        { name: `${prefix}_R1_OHM`, value: String(r1Ohm), part, ref: { part: id } },
        { name: `${prefix}_R2_OHM`, value: String(r2Ohm), part, ref: { part: id } },
      );
    }
  }
  return macros;
}

const oneLine = (text: string): string => text.replace(/[\r\n]+/g, ' ');

/**
 * Generates include/car_config.h from the macros above, with an include guard
 * and a do-not-edit banner. Parts whose definition is missing are skipped.
 * The output depends only on the inputs, so the same car gives byte-identical
 * text. Run checkWiring first: its `macro-clash` rule catches duplicate names.
 */
export function generateCarConfigHeader(car: Car, catalog: Catalog): string {
  const netlist = new Netlist(car, catalog);
  const lines: string[] = [
    '// car_config.h: generated by the Workbench from car.json. Do not edit;',
    '// change the car in the Workbench and this file is rewritten.',
    `// Car: ${oneLine(car.name)}`,
    '',
    '#ifndef CAR_CONFIG_H',
    '#define CAR_CONFIG_H',
    '',
    `#define CAR_WIFI_ENABLED ${car.wifi ? 1 : 0}`,
  ];
  let current: ResolvedPart | undefined;
  for (const macro of headerMacros(netlist)) {
    if (macro.part !== current) {
      current = macro.part;
      const { definition, instance } = macro.part;
      lines.push('', `// ${instance.instanceId}: ${oneLine(definition.name)} (${definition.id})`);
    }
    lines.push(`#define ${macro.name} ${macro.value}`);
  }
  lines.push('', '#endif  // CAR_CONFIG_H', '');
  return lines.join('\n');
}
