import type { Car } from './car.ts';
import type { Catalog } from './catalog.ts';
import { macroName } from './common.ts';
import { Netlist } from './wiring/netlist.ts';

const hex = (address: number): string => `0x${address.toString(16).toUpperCase().padStart(2, '0')}`;

/**
 * Generates include/car_config.h: one `#define` per GPIO-wired pin
 * (`TOF_LEFT_XSHUT_PIN 16`), plus I²C addresses and divider resistor values.
 * Parts whose definition is missing are skipped. The output depends only on
 * the inputs, so the same car gives byte-identical text.
 */
export function generateCarConfigHeader(car: Car, catalog: Catalog): string {
  const netlist = new Netlist(car, catalog);
  const lines: string[] = [
    '// car_config.h: generated by the Workbench from car.json. Do not edit;',
    '// change the car in the Workbench and this file is rewritten.',
    `// Car: ${car.name.replace(/[\r\n]+/g, ' ')}`,
    '',
    '#ifndef CAR_CONFIG_H',
    '#define CAR_CONFIG_H',
    '',
    `#define CAR_WIFI_ENABLED ${car.wifi ? 1 : 0}`,
  ];

  for (const part of netlist.parts) {
    const definition = part.definition;
    const prefix = macroName(part.instance.instanceId);
    const block: string[] = [];

    for (const pin of definition.pins) {
      if (pin.kind === 'gnd' || pin.kind === 'power-in' || pin.kind === 'power-out') continue;
      const gpio = netlist.gpioOfPin(part, pin.name);
      if (gpio !== undefined) block.push(`#define ${prefix}_${macroName(pin.name)}_PIN ${gpio}`);
    }
    if ('i2c' in definition && definition.i2c) {
      block.push(
        `#define ${prefix}_I2C_ADDR ${hex(part.instance.i2cAddress ?? definition.i2c.defaultAddress)}`,
      );
    }
    if ('behavior' in definition && definition.behavior.template === 'voltage-divider') {
      const { r1Ohm, r2Ohm } = definition.behavior.params;
      block.push(`#define ${prefix}_R1_OHM ${r1Ohm}`, `#define ${prefix}_R2_OHM ${r2Ohm}`);
    }

    if (block.length > 0) {
      lines.push(
        '',
        `// ${part.instance.instanceId}: ${definition.name} (${definition.id})`,
        ...block,
      );
    }
  }

  lines.push('', '#endif  // CAR_CONFIG_H', '');
  return lines.join('\n');
}
